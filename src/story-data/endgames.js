// --- pure state helpers (a story: has/get/fact/time; Node tests pass a stub) ------------------------------------------------
const abs = (s) => s.time().abs;
const factDay = (s, k) => { const f = s.fact(k); return f ? f.abs : null; };
export const endDay = (s) => factDay(s, 'end');
export const journalist = (s) => s.has('end.J') || s.get('end') === 'J' || s.get('end') === 'JN';
export const money = (s) => s.has('end.M') || s.get('end') === 'M';
const monthOf = (s) => (typeof s.date === 'function' ? s.date().month : 6);
export const inMonths = (S, m) => !S.months || (m >= S.months[0] && m <= S.months[1]);
// the secret's state: 'none' | 'given' (taken on) | 'found' | 'done' (told)
export function secretState(s, id) {
  if (s.has(`secret.${id}.done`)) return 'done';
  if (s.has(`secret.${id}.found`)) return 'found';
  if (s.has(`secret.${id}.given`)) return 'given';
  return 'none';
}
// the secrets given and not yet told → [id]
export const openSecrets = (s) => SECRET_IDS.filter((id) => { const st = secretState(s, id); return st === 'given' || st === 'found'; });
// may a new secret be told today? (the ending's end.J, FIRST_AFTER days on, SECRET_GAP since the last told, one at a time
// unless the open one is STALE days old)
export function secretReady(s) {
  if (!journalist(s)) return false;
  const e = endDay(s), now = abs(s);
  if (e == null || now - e < FIRST_AFTER) return false;
  const given = SECRET_IDS.map((id) => factDay(s, `secret.${id}.given`)).filter((d) => d != null);
  const last = given.length ? Math.max(...given) : null;
  if (last != null && now - last < SECRET_GAP) return false;
  for (const id of openSecrets(s)) { const d = factDay(s, `secret.${id}.given`); if (d != null && now - d < STALE) return false; }
  return true;
}
// the secret this owner would tell now (or null): theirs, untold, in its months
export function secretFor(s, ep) {
  if (!secretReady(s)) return null;
  const m = monthOf(s);
  return secretsOf(ep).find((S) => secretState(s, S.id) === 'none' && inMonths(S, m)) || null;
}
// the one waiting elsewhere, nearest a store (for the keepers' pointer line): an untold secret in its months
export function secretWaiting(s, fromEp, dist = () => 0) {
  if (!secretReady(s)) return null;
  const m = monthOf(s);
  const list = SECRETS.filter((S) => secretState(s, S.id) === 'none' && inMonths(S, m) && S.owner !== Number(fromEp));
  list.sort((a, b) => dist(fromEp, a.owner) - dist(fromEp, b.owner));
  return list[0] || null;
}
// may this owner ask their softening task today?
export function softReady(s, ep) {
  if (!money(s) || s.has(`owner.${ep}.softened`) || !softOf(ep)) return false;
  const e = endDay(s), now = abs(s);
  if (e == null || now - e < SOFT_FIRST) return false;
  if (s.has(`owner.${ep}.asked`)) return true; // (already asked: asked again only when the job came to nothing: endgames.js)
  const asked = OWNER_EPS.map((x) => factDay(s, `owner.${x}.asked`)).filter((d) => d != null);
  const last = asked.length ? Math.max(...asked) : null;
  return last == null || now - last >= SOFT_GAP;
}
export const softenedCount = (s) => OWNER_EPS.filter((ep) => s.has(`owner.${ep}.softened`)).length;

